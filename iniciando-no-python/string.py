# string é um dos tipos de dados. é texto entre aspas.

print("Oi.")

'''
caso queira colocar aspas dentro da string:
a) use o caractere de escape \, e o caractere seguinte não será interpretado.
b) use aspas diferentes.
'''

print("Hello, \"world!")
print('Hello, "world!')

# caso queira que o caractere de escape \ seja exibido, use r antes da string.

print(r"Hello, \"world!")
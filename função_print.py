# sep=' ' e end='\n' são o padrão.
# 1 e 2 são argumentos não nomeados. sep e end são argumentos nomeados.
# posso alterar o sep e end.

print(1, 2, sep=' ', end='\n')
print(1, 2, sep='--', end='.\n')


